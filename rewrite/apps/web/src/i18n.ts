export type Language = 'sv' | 'en';

const KEY = 'language';

/** The language chosen on this device in Mina inställningar; Swedish until one is (Lars, 2026-10-31). */
function storedLanguage(): Language {
  try {
    return localStorage.getItem(KEY) === 'en' ? 'en' : 'sv';
  } catch {
    return 'sv';
  }
}

/** A public output's viewer or a screen cannot choose: their browser's first language, Swedish or else English. */
export function browserLanguage(): Language {
  return (navigator.languages[0] ?? navigator.language ?? '').toLowerCase().startsWith('sv') ? 'sv' : 'en';
}

let current: Language = storedLanguage();

/** The language this page shows; an open page keeps it until it loads again. */
export const language = (): Language => current;

/** The locale for dates, numbers and the order of names. */
export const locale = (): string => (current === 'sv' ? 'sv-SE' : 'en-GB');

/** Shows the page in `lang`. Call before the first render. */
export function installLanguage(lang: Language = storedLanguage()): void {
  current = lang;
  document.documentElement.lang = lang;
}

/** Chooses the language for this device and loads the page again in it. */
export function setLanguage(lang: Language): void {
  try {
    localStorage.setItem(KEY, lang);
  } catch {
    return; // storage refused: there is nowhere to keep the choice, so nothing changes
  }
  location.reload();
}

/** Every text in both languages. */
export const texts: Record<Language, Record<TextKey, string>> = { sv, en };

/** Whether `key` names a text, for a key made from a reason another part of the app sends. */
export const isTextKey = (key: string): key is TextKey => key in sv;

/** The text for `key` in this page's language, with `{name}` placeholders filled from `vars`. */
export function t(key: TextKey, vars: Record<string, string | number> = {}): string {
  return texts[current][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}
