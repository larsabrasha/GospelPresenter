// The shells' types from the core's views' JSON Schema (views.json, written by examples/schema.rs): Swift structs for
// apps/mac. The schema is as simple as the views: objects of named fields, each a string, an integer, a number, a
// boolean, a list, another type or one of them optional. Run by crates/gp-core/schema/generate.sh; its output is
// checked in, and the check that it is current runs in `pnpm test` (packages/architecture).
//   node generate.mjs views.json swift > ViewTypes.swift
import { readFileSync } from 'node:fs';

const [file, lang] = process.argv.slice(2);
const schema = JSON.parse(readFileSync(file, 'utf8'));
const defs = schema.$defs ?? {};

/** A field's type in Swift, and whether it may be missing or null. */
function swiftType(s) {
  if (s.$ref) return { type: s.$ref.split('/').pop(), optional: false };
  const types = Array.isArray(s.type) ? s.type : [s.type];
  const optional = types.includes('null');
  const t = types.find((x) => x !== 'null');
  const base =
    t === 'string' ? 'String'
    : t === 'integer' ? 'Int'
    : t === 'number' ? 'Double'
    : t === 'boolean' ? 'Bool'
    : t === 'array' ? `[${swiftType(s.items).type}]`
    : (() => { throw new Error(`a type the generator does not know: ${JSON.stringify(s)}`); })();
  return { type: base, optional };
}

/** A doc comment's lines, from a schema's description. */
const doc = (s, indent) => (s.description ? s.description.split('\n').map((l) => `${indent}/// ${l}`.trimEnd()).join('\n') + '\n' : '');

function swift() {
  const out = ['// Generated by crates/gp-core/schema/generate.mjs from the core\'s view types (crates/gp-core/src/view_types.rs).', '// Do not edit: change the Rust type and run crates/gp-core/schema/generate.sh.', 'import Foundation', ''];
  for (const [name, def] of Object.entries(defs).toSorted(([a], [b]) => a.localeCompare(b))) {
    const required = new Set(def.required ?? []);
    out.push(`${doc(def, '')}struct ${name}: Codable, Hashable {`);
    for (const [field, s] of Object.entries(def.properties ?? {})) {
      const { type, optional } = swiftType(s);
      // A field the core may leave out, or one with a default: optional here, so a missing one decodes.
      const maybe = optional || !required.has(field);
      out.push(`${doc(s, '    ')}    let ${field}: ${type}${maybe ? '?' : ''}`);
    }
    out.push('}', '');
  }
  return out.join('\n');
}

if (lang !== 'swift') throw new Error(`no such language: ${lang}`);
process.stdout.write(swift());
