// The shells' types from the core's views' JSON Schema (views.json, written by examples/schema.rs): Swift for apps/mac's
// Shell module, C# for the Windows app (System.Text.Json, .NET 8), TypeScript for the web (packages/rust-core). The
// schema is as plain as the views: objects of named fields, each a string, an integer, a number, a boolean, any JSON,
// a list, another type or one of them optional; a set of strings; and a union tagged by `type` (serde's
// `#[serde(tag = "type")]`), each case its own fields. Run by crates/gp-core/schema/generate.sh; its outputs are checked
// in, and packages/architecture/test/generated.test.ts checks they are current.
//   node generate.mjs views.json swift|csharp|typescript > file
import { readFileSync } from 'node:fs';

const [file, lang] = process.argv.slice(2);
const schema = JSON.parse(readFileSync(file, 'utf8'));
const defs = schema.$defs ?? {};

// ------------------------------------------------------------ the schema, read once

/** A field's type, apart from any language: {kind: string|int|number|bool|any|ref|list|map, of?, ref?}, and nullable. */
function typeOf(s) {
  if (s === true || (typeof s === 'object' && Object.keys(s).filter((k) => k !== 'description').length === 0)) return { kind: 'any', nullable: false };
  if (s.$ref) return { kind: 'ref', ref: s.$ref.split('/').pop(), nullable: false };
  // Option<T> of a type: anyOf [T, null].
  const any = s.anyOf ?? s.oneOf;
  if (any) {
    const rest = any.filter((x) => x.type !== 'null');
    if (rest.length === 1) return { ...typeOf(rest[0]), nullable: any.length > rest.length };
    throw new Error(`a union the generator does not know: ${JSON.stringify(s)}`);
  }
  const types = Array.isArray(s.type) ? s.type : [s.type];
  const nullable = types.includes('null');
  const t = types.find((x) => x !== 'null');
  const kinds = { string: 'string', integer: 'int', number: 'number', boolean: 'bool' };
  if (kinds[t]) return { kind: kinds[t], nullable };
  if (t === 'array') return { kind: 'list', of: typeOf(s.items ?? true), nullable };
  if (t === 'object') return { kind: 'map', of: typeOf(s.additionalProperties ?? true), nullable };
  throw new Error(`a type the generator does not know: ${JSON.stringify(s)}`);
}

/** An object's fields: {field, s, t, optional} (optional: the core may leave it out, or it may be null). */
function fields(def, skip = []) {
  const required = new Set(def.required ?? []);
  return Object.entries(def.properties ?? {}).filter(([f]) => !skip.includes(f)).map(([field, s]) => {
    const t = typeOf(s);
    return { field, s, t, optional: t.nullable || !required.has(field) };
  });
}

/** A union's cases, when every one is an object whose `type` is a constant: [{tag, def, fields}]; else none. */
function tagged(def) {
  const cases = def.oneOf ?? def.anyOf;
  if (!cases || !cases.every((c) => c.properties?.type?.const !== undefined || c.properties?.type?.enum?.length === 1)) return null;
  return cases.map((c) => ({ tag: c.properties.type.const ?? c.properties.type.enum[0], def: c, fields: fields(c, ['type']) }));
}

/** A set of strings: {enum: [...]}, or oneOf constants. */
function strings(def) {
  if (def.type === 'string' && Array.isArray(def.enum)) return def.enum.map((value) => ({ value, def: {} }));
  const cases = def.oneOf;
  if (cases?.every((c) => c.type === 'string' && (c.const !== undefined || c.enum?.length === 1))) return cases.map((c) => ({ value: c.const ?? c.enum[0], def: c }));
  return null;
}

const types = Object.entries(defs).toSorted(([a], [b]) => a.localeCompare(b)).map(([name, def]) => ({ name, def, union: tagged(def), set: strings(def) }));
const pascal = (n) => n[0].toUpperCase() + n.slice(1);
/** A doc comment's lines, from a schema's description, each opened by `mark`. */
const doc = (s, indent, mark = '///') => (s?.description ? s.description.split('\n').map((l) => `${indent}${mark} ${l}`.trimEnd()).join('\n') + '\n' : '');
const HEADER = ['Generated by crates/gp-core/schema/generate.mjs from the core\'s view types (crates/gp-core/src/view_types.rs).', 'Do not edit: change the Rust type and run crates/gp-core/schema/generate.sh.'];

// ------------------------------------------------------------ Swift

const SWIFT_KEYWORDS = new Set(['default', 'in', 'is', 'as', 'case', 'class', 'enum', 'func', 'let', 'var', 'return', 'self', 'struct', 'switch', 'where', 'while', 'repeat', 'protocol', 'extension', 'operator', 'import', 'init', 'internal', 'public', 'private', 'static', 'subscript', 'throws', 'true', 'false', 'nil', 'for', 'if', 'else', 'guard', 'do', 'catch', 'try', 'break', 'continue', 'defer', 'fallthrough', 'Type']);
const sw = (n) => (SWIFT_KEYWORDS.has(n) ? `\`${n}\`` : n);
function swiftType(t) {
  return { string: 'String', int: 'Int', number: 'Double', bool: 'Bool', any: 'JSONValue' }[t.kind]
    ?? (t.kind === 'ref' ? t.ref : t.kind === 'list' ? `[${swiftType(t.of)}]` : `[String: ${swiftType(t.of)}]`);
}
const swiftField = (f) => `${swiftType(f.t)}${f.optional ? '?' : ''}`;

function swiftStruct({ name, def }) {
  const out = [`${doc(def, '')}public struct ${name}: Codable, Hashable, Sendable {`];
  for (const f of fields(def)) out.push(`${doc(f.s, '    ')}    public let ${sw(f.field)}: ${swiftField(f)}`);
  return [...out, '}'].join('\n');
}

function swiftStrings({ name, def, set }) {
  const out = [`${doc(def, '')}public enum ${name}: String, Codable, Hashable, Sendable {`];
  for (const v of set) out.push(`${doc(v.def, '    ')}    case ${sw(v.value)} = "${v.value}"`);
  return [...out, '}'].join('\n');
}

/** A tagged union: a case per tag with its fields, `unknown` for a tag this app does not know (a newer core's). */
function swiftUnion({ name, def, union }) {
  const keys = [...new Set(['type', ...union.flatMap((c) => c.fields.map((f) => f.field))])];
  const out = [`${doc(def, '')}public enum ${name}: Codable, Hashable, Sendable {`];
  for (const c of union) out.push(`${doc(c.def, '    ')}    case ${sw(c.tag)}${c.fields.length ? `(${c.fields.map((f) => `${f.field}: ${swiftField(f)}`).join(', ')})` : ''}`);
  out.push('    /// A case this app does not know (a newer core\'s): its tag, to be left alone.', '    case unknown(String)', '');
  out.push(`    private enum CodingKeys: String, CodingKey { case ${keys.map(sw).join(', ')} }`, '');
  out.push('    public init(from decoder: Decoder) throws {', '        let c = try decoder.container(keyedBy: CodingKeys.self)', '        switch try c.decode(String.self, forKey: .type) {');
  for (const c of union) {
    const args = c.fields.map((f) => `${f.field}: try c.${f.optional ? 'decodeIfPresent' : 'decode'}(${swiftType(f.t)}.self, forKey: .${sw(f.field)})`).join(', ');
    out.push(`        case "${c.tag}": self = .${sw(c.tag)}${c.fields.length ? `(${args})` : ''}`);
  }
  out.push('        case let other: self = .unknown(other)', '        }', '    }', '');
  out.push('    public func encode(to encoder: Encoder) throws {', '        var c = encoder.container(keyedBy: CodingKeys.self)', '        switch self {');
  for (const c of union) {
    const bind = c.fields.length ? `let .${sw(c.tag)}(${c.fields.map((f) => f.field).join(', ')})` : `.${sw(c.tag)}`;
    const body = [`try c.encode("${c.tag}", forKey: .type)`, ...c.fields.map((f) => `try c.${f.optional ? 'encodeIfPresent' : 'encode'}(${f.field}, forKey: .${sw(f.field)})`)];
    out.push(`        case ${bind}:`, ...body.map((l) => `            ${l}`));
  }
  out.push('        case let .unknown(tag): try c.encode(tag, forKey: .type)', '        }', '    }', '}');
  return out.join('\n');
}

const swift = () => [...HEADER.map((l) => `// ${l}`), 'import Foundation', '', ...types.flatMap((t) => [t.union ? swiftUnion(t) : t.set ? swiftStrings(t) : swiftStruct(t), ''])].join('\n');

// ------------------------------------------------------------ C# (System.Text.Json, .NET 8)

function csType(t) {
  return { string: 'string', int: 'long', number: 'double', bool: 'bool', any: 'JsonElement' }[t.kind]
    ?? (t.kind === 'ref' ? t.ref : t.kind === 'list' ? `IReadOnlyList<${csType(t.of)}>` : `IReadOnlyDictionary<string, ${csType(t.of)}>`);
}
/** A record's parameters; one named as its record (C# forbids it: a union's `message` case) gets `Value` after it. */
const csParams = (fs, owner = '') => fs.map((f) => {
  const n = pascal(f.field) === owner ? `${pascal(f.field)}Value` : pascal(f.field);
  return `[property: JsonPropertyName("${f.field}")] ${csType(f.t)}${f.optional ? '?' : ''} ${n}`;
}).join(', ');
const csDoc = (s, indent) => (s?.description ? `${indent}/// <summary>${s.description.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('\n', ' ')}</summary>\n` : '');

function csStruct({ name, def }) {
  return `${csDoc(def, '')}public sealed record ${name}(${csParams(fields(def), name)});`;
}

function csStrings({ name, def, set }) {
  // The member names are the values themselves, so the converter writes and reads them as they are.
  return [`${csDoc(def, '')}[JsonConverter(typeof(JsonStringEnumConverter<${name}>))]`, `public enum ${name}`, '{', ...set.map((v) => `${csDoc(v.def, '    ')}    ${v.value},`), '}'].join('\n');
}

/** A tagged union: an abstract record, a case of it per tag and `Unknown` for a tag this app does not know (a newer
 * core's), read and written by a converter of its own: .NET 8's polymorphism throws on an unknown tag. */
function csUnion({ name, def, union }) {
  const caseName = (c) => pascal(c.tag);
  const param = (c, f) => (pascal(f.field) === caseName(c) ? `${pascal(f.field)}Value` : pascal(f.field));
  const out = [`${csDoc(def, '')}[JsonConverter(typeof(${name}Converter))]`, `public abstract record ${name}`, '{'];
  for (const c of union) out.push(`${csDoc(c.def, '    ')}    public sealed record ${caseName(c)}(${csParams(c.fields, caseName(c))}) : ${name};`);
  out.push(`    /// <summary>A case this app does not know (a newer core's): its tag, to be left alone.</summary>`, `    public sealed record Unknown(string Type) : ${name};`, '}', '');
  out.push(`public sealed class ${name}Converter : JsonConverter<${name}>`, '{');
  out.push(`    public override ${name} Read(ref Utf8JsonReader reader, System.Type type, JsonSerializerOptions options)`, '    {');
  out.push('        using var doc = JsonDocument.ParseValue(ref reader);', '        var e = doc.RootElement;', '        var tag = e.TryGetProperty("type", out var t) ? t.GetString() ?? "" : "";', '        return tag switch', '        {');
  for (const c of union) {
    const args = c.fields.map((f) => `ViewJson.Field<${csType(f.t)}${f.optional ? '?' : ''}>(e, "${f.field}", options)${f.optional ? '' : '!'}`).join(', ');
    out.push(`            "${c.tag}" => new ${name}.${caseName(c)}(${args}),`);
  }
  out.push(`            _ => new ${name}.Unknown(tag),`, '        };', '    }', '');
  out.push(`    public override void Write(Utf8JsonWriter writer, ${name} value, JsonSerializerOptions options)`, '    {', '        writer.WriteStartObject();', '        switch (value)', '        {');
  for (const c of union) {
    out.push(`            case ${name}.${caseName(c)} x:`, `                writer.WriteString("type", "${c.tag}");`);
    for (const f of c.fields) out.push(`                ViewJson.Write(writer, "${f.field}", x.${param(c, f)}, options);`);
    out.push('                break;');
  }
  out.push(`            case ${name}.Unknown x:`, '                writer.WriteString("type", x.Type);', '                break;', '        }', '        writer.WriteEndObject();', '    }', '}');
  return out.join('\n');
}

/** What the unions' converters share: a field read (missing or null its default), and one written (null left out). */
const CS_HELPERS = `/// <summary>What the unions' converters share.</summary>
internal static class ViewJson
{
    internal static T? Field<T>(JsonElement e, string name, JsonSerializerOptions options) =>
        e.TryGetProperty(name, out var v) && (v.ValueKind != JsonValueKind.Null || typeof(T) == typeof(JsonElement)) ? v.Deserialize<T>(options) : default;

    internal static void Write<T>(Utf8JsonWriter writer, string name, T value, JsonSerializerOptions options)
    {
        if (value is null) return;
        writer.WritePropertyName(name);
        JsonSerializer.Serialize(writer, value, options);
    }
}`;

const csharp = () => [...HEADER.map((l) => `// ${l}`), '#nullable enable', 'using System.Collections.Generic;', 'using System.Text.Json;', 'using System.Text.Json.Serialization;', '', 'namespace GospelPresenter.Core;', '',
  ...types.flatMap((t) => [t.union ? csUnion(t) : t.set ? csStrings(t) : csStruct(t), '']), CS_HELPERS, ''].join('\n');

// ------------------------------------------------------------ TypeScript

function tsType(t) {
  return { string: 'string', int: 'number', number: 'number', bool: 'boolean', any: 'unknown' }[t.kind]
    ?? (t.kind === 'ref' ? t.ref : t.kind === 'list' ? `${tsType(t.of)}[]` : `Record<string, ${tsType(t.of)}>`);
}
const tsFields = (fs, indent) => fs.map((f) => `${doc(f.s, indent, '//')}${indent}${f.field}${f.optional ? '?' : ''}: ${tsType(f.t)}${f.t.nullable ? ' | null' : ''};`);
const tsStruct = ({ name, def }) => [`${doc(def, '', '//')}export interface ${name} {`, ...tsFields(fields(def), '  '), '}'].join('\n');
const tsStrings = ({ name, def, set }) => `${doc(def, '', '//')}export type ${name} = ${set.map((v) => `'${v.value}'`).join(' | ')};`;
const tsUnion = ({ name, def, union }) => [`${doc(def, '', '//')}export type ${name} =`, ...union.map((c) => `  | { type: '${c.tag}'${c.fields.map((f) => `; ${f.field}${f.optional ? '?' : ''}: ${tsType(f.t)}${f.t.nullable ? ' | null' : ''}`).join('')} }`)].join('\n') + ';';

const typescript = () => [...HEADER.map((l) => `// ${l}`), '', ...types.flatMap((t) => [t.union ? tsUnion(t) : t.set ? tsStrings(t) : tsStruct(t), ''])].join('\n');

const emit = { swift, csharp, typescript }[lang];
if (!emit) throw new Error(`no such language: ${lang}`);
process.stdout.write(emit());
