// The web's UI texts (apps/web/src/i18n.ts), Swedish and English, as a Swift file the app reads them from
// (Sources/GPMac/TextTable.swift, not kept in git): one table for the web and the native apps, so a text is written
// once. The JSON goes into a raw string literal, which Swift compiles at once where a dictionary literal of 2 500
// entries would take the type checker minutes. Written only when it changed. apple.sh and crates/gp-core/build.sh run it.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const { texts } = await import(join(here, '../web/src/i18n.ts'));
const json = JSON.stringify(texts);
if (json.includes('"#')) throw new Error('a text holds "#, which would end the Swift raw string');
/** Writes `file` when its text changed. */
function write(file, swift) {
  const out = join(here, 'Sources/GPMac', file);
  let old = '';
  try {
    old = readFileSync(out, 'utf8');
  } catch {}
  if (old !== swift) writeFileSync(out, swift);
}
write('TextTable.swift', `// Generated by apps/mac/texts.mjs from apps/web/src/i18n.ts; not kept in git.\nlet textTable = #"${json}"#\n`);

// The colours and the buttons' roles, the core's (`lookView`, crates/gp-core/src/look.rs), the same way: one table for
// every shell, read before the app has a database.
// The core's TypeScript wrapper has more than types to strip, so it is read by a Node that transforms it.
const core = join(here, '../../packages/rust-core/src/node.ts');
const read = `const { nodeRustCore } = await import(${JSON.stringify(core)}); process.stdout.write(JSON.stringify(nodeRustCore().pure('lookView', {})));`;
const look = execFileSync(process.execPath, ['--experimental-transform-types', '--no-warnings', '--input-type=module', '-e', read], { encoding: 'utf8' });
// ##"…"##: a colour's "#rrggbb" holds "#, which would end a #"…"#.
if (look.includes('"##')) throw new Error('the look holds "##, which would end the Swift raw string');
write('LookTable.swift', `// Generated by apps/mac/texts.mjs from the core's lookView; not kept in git.\nlet lookTable = ##"${look}"##\n`);

// The accent as the bundle's AccentColor (apps/mac/bundle.sh compiles it into Assets.car), light and dark: what a Mac's
// sidebar selection and its icons take, which no SwiftUI modifier reaches.
const { accent, colors, app } = JSON.parse(look);
// The app's name and icon, the core's too: bundle.sh reads them from here.
mkdirSync(join(here, 'build'), { recursive: true });
writeFileSync(join(here, 'build/app.env'), `APP_NAME=${JSON.stringify(app.name)}\nAPP_ICON=${JSON.stringify(join(here, '../..', app.icon))}\n`);
const component = (hex, at) => (parseInt(hex.slice(at, at + 2), 16) / 255).toFixed(3);
const rgb = (hex) => ({ 'color-space': 'srgb', components: { red: component(hex, 1), green: component(hex, 3), blue: component(hex, 5), alpha: '1.000' } });
const colorset = {
  colors: [
    { idiom: 'universal', color: rgb(colors[accent].light.hex) },
    { idiom: 'universal', appearances: [{ appearance: 'luminosity', value: 'dark' }], color: rgb(colors[accent].dark.hex) },
  ],
  info: { author: 'xcode', version: 1 },
};
const assets = join(here, 'build/Assets.xcassets');
mkdirSync(join(assets, 'AccentColor.colorset'), { recursive: true });
writeFileSync(join(assets, 'Contents.json'), JSON.stringify({ info: { author: 'xcode', version: 1 } }, null, 2));
writeFileSync(join(assets, 'AccentColor.colorset/Contents.json'), JSON.stringify(colorset, null, 2));
